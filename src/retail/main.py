"""Точка входа учебного проекта.

На исследовательском этапе содержит перечень этапов основного
бизнес-процесса сети магазинов у дома. Алгоритмы автоматизации
будут реализованы на аналитическом этапе практики.
"""

PROCESS_STAGES = [
    "Формирование ассортиментной матрицы",
    "Заключение договоров с поставщиками",
    "Централизованная закупка",
    "Доставка товара в магазины",
    "Приёмка и выкладка товара",
    "Ценообразование и проведение промоакций",
    "Продажа товара покупателю",
    "Учёт продаж и остатков",
    "Списание и возврат товара",
    "Формирование отчётности",
]


def print_process() -> None:
    """Выводит этапы основного бизнес-процесса."""
    print("Основной бизнес-процесс сети магазинов у дома:")
    for number, stage in enumerate(PROCESS_STAGES, start=1):
        print(f"{number:>2}. {stage}")


if __name__ == "__main__":
    print_process()
